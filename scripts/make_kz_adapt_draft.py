def norm(t: str) -> str:
    return re.sub(r"\s+", " ", t.lower()).strip()


def shingles(t: str) -> set[str]:
    t = norm(t)
    return {t[i:i + NGRAM] for i in range(max(1, len(t) - NGRAM + 1))}


def minhash(s: set[str]) -> MinHash:
    m = MinHash(num_perm=PERM, seed=1)
    for x in s:
        m.update(x.encode("utf-8"))
    return m


def main():
    rows = []
    counter = {}
    for label, category, en, ru, kk in IDEAS:
        counter[label] = counter.get(label, 0) + 1
        for lang, text in (("en", en), ("ru", ru), ("kk", kk)):
            rows.append({"id": f"ad_{label}_{counter[label]:02d}_{lang}", "category": category,
                         "same_category_as_test": str(category in TEST_CATEGORIES).lower(), "language": lang,
                         "text": text, "label": label})
    with open(ROOT / "data" / "kz_cases" / "cases.csv", encoding="utf-8") as f:
        cases = list(csv.DictReader(f))
    lsh = MinHashLSH(threshold=THRESHOLD, num_perm=PERM)
    case_sh = {}
    for c in cases:
        case_sh[c["id"]] = shingles(c["text"])
        lsh.insert(c["id"], minhash(case_sh[c["id"]]))
    keep, removed = [], []
    for r in rows:
        s = shingles(r["text"])
        hits = []
        for cid in lsh.query(minhash(s)):
            j = len(s & case_sh[cid]) / len(s | case_sh[cid])
            if j >= THRESHOLD:
                hits.append((cid, j))
        if hits:
            cid, j = max(hits, key=lambda x: x[1])
            removed.append({**r, "closest_case": cid, "jaccard": round(j, 4)})
        else:
            keep.append(r)
    out = ROOT / "data" / "kz_adapt"
    out.mkdir(parents=True, exist_ok=True)
    fields = ["id", "category", "same_category_as_test", "language", "text", "label"]
    with open(out / "draft.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        w.writerows(keep)
    with open(out / "overlap_removed.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields + ["closest_case", "jaccard"], lineterminator="\n")
        w.writeheader()
        w.writerows(removed)
    print(f"{len(rows)} written, {len(removed)} removed for overlap (Jaccard >= {THRESHOLD}), {len(keep)} kept")


if __name__ == "__main__":
    main()
