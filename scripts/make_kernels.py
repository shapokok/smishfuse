"""Writes kaggle/kernels/<name>/{kernel-metadata.json, <name>.ipynb} from configs/kaggle_kernels.yaml.

The notebook is a thin wrapper: it copies the code dataset to /kaggle/working/code,
installs the listed packages and runs src/kaggle_entry.py with the kernel's spec.
Run: python scripts/make_kernels.py [name ...]
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "kaggle" / "kernels"

SETUP = r'''import glob, json, os, shutil, subprocess, sys, tarfile, zipfile
KERNEL = {kernel!r}
SPEC = json.loads({spec!r})
PIP = {pip!r}

def find_code():
    hits = sorted(glob.glob("/kaggle/input/**/configs/step3.yaml", recursive=True))
    if hits:
        return os.path.dirname(os.path.dirname(hits[0]))
    # The code dataset may arrive as archives: unpack them and search again.
    tmp = "/tmp/smishfuse_code"
    for a in glob.glob("/kaggle/input/**/smishfuse-code/**/*", recursive=True):
        if a.endswith(".zip"):
            zipfile.ZipFile(a).extractall(os.path.join(tmp, os.path.basename(a)[:-4]))
        elif a.endswith((".tar", ".tar.gz", ".tgz")):
            tarfile.open(a).extractall(tmp)
    hits = sorted(glob.glob(tmp + "/**/configs/step3.yaml", recursive=True))
    if not hits:
        raise SystemExit("smishfuse-code not found")
    return os.path.dirname(os.path.dirname(hits[0]))

code = find_code()
shutil.copytree(code, "/kaggle/working/code", dirs_exist_ok=True)
print("code from", code)
if PIP:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *PIP], check=True)
'''

RUN = r'''import subprocess, sys
p = subprocess.Popen([sys.executable, "/kaggle/working/code/src/kaggle_entry.py", "--kernel", KERNEL,
                      "--spec", json.dumps(SPEC)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
for line in p.stdout:
    print(line, end="", flush=True)
rc = p.wait()
print("exit code", rc)
if rc:
    raise SystemExit(rc)
'''


def notebook(cells: list[tuple[str, str]]) -> dict:
    return {
        "cells": [{"cell_type": t, "metadata": {}, "source": src.splitlines(keepends=True),
                   **({"outputs": [], "execution_count": None} if t == "code" else {})} for t, src in cells],
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                     "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 5,
    }


def main(names):
    cfg = yaml.safe_load((ROOT / "configs" / "kaggle_kernels.yaml").read_text(encoding="utf-8"))
    owner = cfg["owner"]
    for name, k in cfg["kernels"].items():
        if names and name not in names:
            continue
        d = OUT / name
        d.mkdir(parents=True, exist_ok=True)
        gpu = k["accelerator"] != "none"
        meta = {
            "id": f"{owner}/{name}", "title": name, "code_file": f"{name}.ipynb", "language": "python",
            "kernel_type": "notebook", "is_private": True, "enable_gpu": gpu, "enable_tpu": False,
            "enable_internet": True, "dataset_sources": [f"{owner}/{ds}" for ds in cfg["datasets"]],
            "competition_sources": [], "kernel_sources": k.get("kernel_sources", []), "model_sources": [],
        }
        if gpu:
            meta["machine_shape"] = k["accelerator"]
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
        cells = [
            ("markdown", f"# {name}\n\nGenerated by `scripts/make_kernels.py` (SmishFuse). Spec:\n\n"
                         f"```json\n{json.dumps(k['spec'], indent=1)}\n```\n"),
            ("code", SETUP.format(kernel=name, spec=json.dumps(k["spec"]), pip=cfg["pip"][k["pip"]] if k.get("pip") else [])),
            ("code", RUN),
        ]
        (d / f"{name}.ipynb").write_text(json.dumps(notebook(cells), indent=1) + "\n", encoding="utf-8")
        print(f"wrote {d}")


if __name__ == "__main__":
    main(sys.argv[1:])
