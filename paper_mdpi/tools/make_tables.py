def corpora() -> str:
    names = {"mendeley": ("Mendeley SMS Phishing \\cite{mendeley2022}", "EN"),
             "moz_smishing": ("MOZ-Smishing \\cite{moz2025}", "PT"),
             "super_sms_clean": ("Super SMS, clean$^{a}$ \\cite{salman2024}", "EN"),
             "uci_sms": ("UCI SMS Spam$^{b}$ \\cite{almeida2011}", "EN")}
    rows = []
    for key, (label, lang) in names.items():
        if key == "super_sms_clean":
            d, c = js("dedup_super_sms.json"), js("super_sms_clean.json")
            before = d["rows_before"]
            removed = f"{d['rows_before'] - d['rows_after']} + {c['rows_before'] - c['rows_after']}"
            kept, labels = c["rows_after"], c["labels_after"]
        else:
            d = js(f"dedup_{key}.json")
            before, removed, kept, labels = d["rows_before"], d["rows_before"] - d["rows_after"], d["rows_after"], d["labels_after"]
        if key == "uci_sms":
            parts = ["\\multicolumn{3}{c}{not split}"]
        else:
            sp = js(f"split_{key}.json")["labels"]
            parts = [str(sum(sp[s].values())) for s in ("train", "val", "test")]
        cls = [str(labels[c]) if c in labels else "--" for c in ("ham", "smishing", "spam")]
        if set(labels) - {"ham", "smishing", "spam"}:
            raise ValueError(f"{key}: unexpected classes {sorted(labels)}")
        rows.append(" & ".join([label, lang, str(before), str(removed), str(kept), *parts, *cls]) + " \\\\")
    head = [" & & & & & \\multicolumn{3}{c}{Split} & \\multicolumn{3}{c}{Classes (kept)} \\\\",
            "\\cmidrule(lr){6-8}\\cmidrule(lr){9-11}",
            "Corpus & Lang. & Before & Removed & Kept & Train & Val & Test & ham & smishing & spam \\\\"]
    note = ("Before: valid messages after loading. Removed: exact and near duplicates of a kept message, "
            "minority-label members of label-conflict groups and whole groups without a majority label "
            "(Section~\\ref{sec:data}). Splits are stratified by class. "
            "$^{a}$ Removed within the corpus + removed because of an exact or near match in the Mendeley or UCI "
            "corpus. $^{b}$ Used only to measure the overlap with the other corpora.")
    return wrap("tab:corpora", "Corpora after deduplication: messages before and after, splits and classes",
                "lcCCCCCCCCC", head, rows, note, size="\\footnotesize", sep="4pt")


# ---------------------------------------------------------------- helpers for the result tables

_M = None


def metrics() -> pd.DataFrame:
    global _M
    if _M is None:
        _M = pd.read_csv(FINAL / "metrics.csv")
    return _M


def vals(cond: str, test: str, model: str, col: str = "macro_f1") -> pd.Series:
    m = metrics()
    return m[(m.condition == cond) & (m.test_set == test) & (m.model == model)][col].dropna()


def mean_of(cond, test, model, col="macro_f1") -> float:
    v = vals(cond, test, model, col)
    return float(v.mean()) if len(v) else float("nan")


def cell(cond, test, model, col="macro_f1", sd=True, digits=4, bold=False) -> str:
    v = vals(cond, test, model, col)
    if not len(v):
        return "--"
    if len(v) != 5:
        raise ValueError(f"{cond}/{test}/{model}/{col}: {len(v)} seeds")
    txt = f"{v.mean():.{digits}f}"
    if bold:
        txt = f"\\textbf{{{txt}}}"
    return txt + (f" $\\pm$ {v.std(ddof=1):.{digits}f}" if sd else "")


def stacked(cond, test, model, bold=False) -> str:
    """Mean over the standard deviation in one cell (keeps 8 pt type in tables with many columns)."""
    v = vals(cond, test, model)
    if not len(v):
        return "--"
    if len(v) != 5:
        raise ValueError(f"{cond}/{test}/{model}: {len(v)} seeds")
    m = f"{v.mean():.4f}"
    m = f"\\textbf{{{m}}}" if bold else m
    return f"\\begin{{tabular}}[t]{{@{{}}c@{{}}}}{m}\\\\$\\pm${v.std(ddof=1):.4f}\\end{{tabular}}"


def best_in(cond, test, models, col="macro_f1", low=False) -> str | None:
    xs = {x: mean_of(cond, test, x, col) for x in models}
    xs = {k: v for k, v in xs.items() if not math.isnan(v)}
    if not xs:
        return None
    return (min if low else max)(xs, key=xs.get)


def sgn(x: float, digits: int = 2) -> str:
    return f"$-${abs(x):.{digits}f}" if x < 0 else f"$+${x:.{digits}f}"


def pval(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def wrap(label: str, caption: str, colspec: str, head: list[str], body: list[str], note: str, wide=True,
         size="\\small", sep=None) -> str:
    """MDPI table: caption above, booktabs rules, note below; wide tables extend into the left margin."""
    width = "\\fulllength" if wide else "\\textwidth"
    out = ["\\begin{table}[H]", f"\\caption{{{caption}\\label{{{label}}}}}"]
    if wide:
        out.append("\\begin{adjustwidth}{-\\extralength}{0cm}")
    out.append(size)
    if sep:
        out.append(f"\\setlength{{\\tabcolsep}}{{{sep}}}")
    out += [f"\\begin{{tabularx}}{{{width}}}{{{colspec}}}", "\\toprule", *head, "\\midrule", *body,
            "\\bottomrule", "\\end{tabularx}", f"\\noindent{{\\footnotesize{{{note}}}}}"]
    if wide:
        out.append("\\end{adjustwidth}")
    out.append("\\end{table}")
    return HEADER + "\n".join(out) + "\n"


