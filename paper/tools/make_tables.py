# ---------------------------------------------------------------- T8 duplicate inflation

INFL = ["linear_svm", "logreg", "mahmud2024_cnn_bigru", "shim2024_bert_base", "shim2024_distilbert_base",
        "shim2024_roberta_base"]
TASK_LABEL = {"mendeley_3class": "3 classes", "mendeley_binary": "ham vs mal.", "smishing_vs_spam": "smish. vs spam"}


def inflation_rows() -> list[dict]:
    out = []
    for mdl in INFL:
        d = ROOT / "results" / "step5a" / "inflation" / mdl
        res = {v: [json.loads(f.read_text()) for f in sorted(d.glob(f"{v}_seed*.json"))] for v in ("dirty", "clean")}
        row = {"model": mdl, "task": res["dirty"][0]["task"], "n_dirty": res["dirty"][0]["n"], "n_clean": res["clean"][0]["n"]}
        for metric in ("accuracy", "macro_f1"):
            dv = pd.Series([r[metric] for r in res["dirty"]])
            cv = pd.Series([r[metric] for r in res["clean"]])
            row[f"{metric}_dirty"], row[f"{metric}_clean"] = dv.mean(), cv.mean()
            row[f"{metric}_diff"] = 100 * (dv.mean() - cv.mean())
            row[f"{metric}_tol"] = 100 * max(dv.std(ddof=1), cv.std(ddof=1))
        dup = [sum(f["n_test_with_duplicate_in_train"] for f in r["folds"]) / r["n"] for r in res["dirty"]]
        row["dup_share"] = 100 * sum(dup) / len(dup)
        row["n_seeds"] = len(res["dirty"])
        out.append(row)
    return out


def inflation_table() -> str:
    body = []
    for r in inflation_rows():
        cells = [name(r["model"]), TASK_LABEL[r["task"]], f"{r['n_dirty']}/{r['n_clean']}"]
        for metric in ("accuracy", "macro_f1"):
            beyond = "" if abs(r[f"{metric}_diff"]) > r[f"{metric}_tol"] else "$^{a}$"
            cells += [f"{r[f'{metric}_dirty']:.4f}", f"{r[f'{metric}_clean']:.4f}", f"{sgn(r[f'{metric}_diff'])}{beyond}"]
        cells.append(f"{r['dup_share']:.1f}")
        body.append(" & ".join(cells) + " \\\\")
    head = [" & & & \\multicolumn{3}{c}{Accuracy} & \\multicolumn{3}{c}{Macro F1} & \\\\",
            "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}",
            "Model & Task & $n$ dirty/clean & dirty & clean & $\\Delta$, pp & dirty & clean & $\\Delta$, pp & dup., \\% \\\\"]
    note = ("Five-fold cross-validation on the training and validation parts of the Mendeley corpus; mean over "
            "3 seeds. Dirty: all raw messages except those whose duplicate group is kept in our test part, with "
            "the raw labels; clean: our deduplicated data. dup.: share of dirty test-fold messages with a duplicate "
            "in the training folds. $^{a}$ difference within the larger seed standard deviation.")
    return wrap("tab:inflation", "Effect of duplicates on cross-validated scores (dirty minus clean data)",
                "lllccccccc", head, body, note, sep="2.5pt")


def build() -> dict[str, str]:
    return {"corpora.tex": corpora(), "main.tex": main_table(), "settings.tex": settings_table(),
            "robustness.tex": robustness_table(), "lowdata.tex": lowdata_table(),
            "efficiency.tex": efficiency_table(), "significance.tex": significance_table(),
            "inflation.tex": inflation_table()}


if __name__ == "__main__":
    (PAPER / "tables").mkdir(exist_ok=True)
    for name, content in build().items():
        (PAPER / "tables" / name).write_text(content, encoding="utf-8")
        print(f"wrote paper/tables/{name}")
