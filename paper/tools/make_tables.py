def significance_table() -> str:
    s = pd.read_csv(FINAL / "significance.csv")
    s = s[s.comparison == "best_baseline"]
    order = list(COND_LABEL)
    tests = ["clean", "train05", "train10", "train20", "heldout05", "heldout10", "heldout20", "zeroshot", "finetune10"]
    s = s.assign(o1=s.condition.map(order.index), o2=s.test_set.map(tests.index)).sort_values(["o1", "o2"])
    body = []
    for r in s.itertuples():
        pb = pval(r.p_bootstrap_holm)
        pm = pval(r.p_mcnemar_holm)
        pb = f"\\textbf{{{pb}}}" if r.significant_bootstrap_holm else pb
        pm = f"\\textbf{{{pm}}}" if r.significant_mcnemar_holm else pm
        body.append(" & ".join([COND_LABEL[r.condition], SETS[r.test_set], name(r.other),
                                f"{r.mean_macro_f1_cascade:.4f}", f"{r.mean_macro_f1_other:.4f}",
                                sgn(100 * r.diff_macro_f1_seed1),
                                f"[{sgn(100 * r.ci95_low)}, {sgn(100 * r.ci95_high)}]",
                                f"{r.mcnemar_b_cascade_only_correct}/{r.mcnemar_c_other_only_correct}", pb, pm]) + " \\\\")
