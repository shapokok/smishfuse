"""Tables of the paper, generated from reports/ and results/ (no number is typed by hand).

build() returns {file name: LaTeX}; paper/check_numbers.py compares it with paper/tables/.
Run: python paper/tools/make_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / "paper"
STATS = ROOT / "reports" / "stats"

HEADER = "% Generated by paper/tools/make_tables.py. Do not edit by hand.\n"


def js(name: str) -> dict:
    return json.loads((STATS / name).read_text())


def corpora() -> str:
    names = {"mendeley": ("Mendeley SMS Phishing \\cite{mendeley2022}", "EN"),
             "moz_smishing": ("MOZ-Smishing \\cite{moz2025}", "PT"),
             "super_sms_clean": ("Super SMS, clean$^{b}$ \\cite{salman2024}", "EN"),
             "uci_sms": ("UCI SMS Spam$^{c}$ \\cite{almeida2011}", "EN")}
    rows = []
    for key, (label, lang) in names.items():
        if key == "super_sms_clean":
            d, c = js("dedup_super_sms.json"), js("super_sms_clean.json")
            before = d["rows_before"]
            removed = f"{d['rows_before'] - d['rows_after']} + {c['rows_before'] - c['rows_after']}"
            kept, labels = c["rows_after"], c["labels_after"]
        else:
            d = js(f"dedup_{key}.json")
            before, removed, kept, labels = d["rows_before"], d["rows_before"] - d["rows_after"], d["rows_after"], d["labels_after"]
        if key == "uci_sms":
            parts = ["\\multicolumn{3}{c}{not split}"]
        else:
            sp = js(f"split_{key}.json")["labels"]
            parts = [str(sum(sp[s].values())) for s in ("train", "val", "test")]
        cls = ", ".join(f"{k} {v}" for k, v in sorted(labels.items()))
        rows.append(" & ".join([label, lang, str(before), str(removed), str(kept), *parts, cls]) + " \\\\")
    return HEADER + "\n".join([
        "\\begin{table*}[t]",
        "\\caption{Corpora after deduplication: messages before and after, splits and classes$^{a}$}",
        "\\label{tab:corpora}",
        "\\centering\\small",
        "\\begin{tabular}{llrrrrrrl}",
        "\\hline",
        "Corpus & Lang. & Before & Removed & Kept & Train & Val & Test & Classes (kept) \\\\",
        "\\hline",
        *rows,
        "\\hline",
        "\\end{tabular}",
        "\\par\\smallskip\\footnotesize",
        "$^{a}$ Before: valid messages after loading. Removed: exact and near duplicates of a kept message, "
        "minority-label members of label-conflict groups and whole groups without a majority label "
        "(Section~\\ref{sec:data}). Splits are stratified by class. "
        "$^{b}$ Removed within the corpus + removed because of an exact or near match in the Mendeley or UCI "
        "corpus. $^{c}$ Used only to measure the overlap with the other corpora.",
        "\\end{table*}", ""])


def build() -> dict[str, str]:
    return {"corpora.tex": corpora()}


if __name__ == "__main__":
    (PAPER / "tables").mkdir(exist_ok=True)
    for name, content in build().items():
        (PAPER / "tables" / name).write_text(content, encoding="utf-8")
        print(f"wrote paper/tables/{name}")
